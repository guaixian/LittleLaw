  /// 当前语言代码:''(跟随系统)/ 'zh' / 'en'。
  static String code = '';

  /// [key] 查询;[args] 支持 {n} {name} {e} 占位替换。
  static String t(String key, [Map<String, Object?>? args]) {
    var value = switch (code) {
      'en' => _en[key] ?? _zh[key] ?? key,
      _ => _zh[key] ?? key,
    };
    if (args != null) {
      args.forEach((k, v) => value = value.replaceAll('{$k}', '$v'));
    }
    return value;
  }

  static const _prefKey = 'app_locale';

  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    code = prefs.getString(_prefKey) ?? '';
  }

  static Future<void> set(String newCode) async {
    code = newCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, newCode);
  }

  /// MaterialApp.locale 解析。
  static Locale? localeOf(BuildContext context) {
    if (code == 'zh') return const Locale('zh');
    if (code == 'en') return const Locale('en');
    return null; // 跟随系统
  }
